function esc(str) {
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function normalize(text) {
  return (text || "")
    .toLowerCase()
    .replace(/\u200b/g, "")
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function buildMcq() {
  mcqList.innerHTML = mcqData.map(q => {
    const opts = q.options.map((opt, idx) => {
      const letter = String.fromCharCode(97 + idx);
      return `
        <label class="option">
          <input type="radio" name="mcq-${q.num}" value="${String.fromCharCode(65 + idx)}" />
          <span><strong>${letter}.</strong> ${esc(opt)}</span>
        </label>`;
    }).join("");

    return `
      <article class="question-card" data-q="${q.num}">
        <div class="question-top">
          <span class="qnum">${q.num}</span>
          <div class="qtext">${esc(q.question)}</div>
        </div>
        <div class="options">${opts}</div>
        <div class="answer-line" id="mcq-feedback-${q.num}"></div>
      </article>`;
  }).join("");
}

