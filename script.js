function phraseMatches(text, phrase) {
  return normalize(text).includes(normalize(phrase));
}

function gradeEssayAnswer(answer, groups) {
  const cleaned = normalize(answer);
  if (!cleaned) return { score: 0, matched: 0, total: groups.length };

  let matched = 0;
  groups.forEach(group => {
    const hit = group.some(phrase => cleaned.includes(normalize(phrase)));
    if (hit) matched += 1;
  });

  const total = groups.length;
  const coverage = matched / total;
  let score = 0;
  if (coverage >= 0.84) score = 1;
  else if (coverage >= 0.5) score = 0.5;
  else score = 0;

  return { score, matched, total };
}

function gradeAll() {
  let totalScore = 0;
  let mcqCorrect = 0;
  let essayScore = 0;
  const feedback = [];

  mcqData.forEach(q => {
    const selected = document.querySelector(`input[name="mcq-${q.num}"]:checked`);
    const feedbackEl = document.getElementById(`mcq-feedback-${q.num}`);
    const correct = q.answer;
    const chosen = selected ? selected.value : null;
    const isCorrect = chosen === correct;
    if (isCorrect) {
      mcqCorrect += 1;
      totalScore += 1;
      feedbackEl.innerHTML = `<span class="correct">benar</span> • jawaban ${correct}`;
    } else {
      feedbackEl.innerHTML = `<span class="wrong">salah</span> • jawaban benar: ${correct}`;
    }
    feedback.push({
      title: `Soal ${q.num}`,
      status: isCorrect ? "benar" : "salah",
      detail: `Kunci: ${correct}`
    });
  });

  essayData.forEach(q => {
    const input = document.getElementById(`essay-${q.num}`);
    const feedbackEl = document.getElementById(`essay-feedback-${q.num}`);
    const result = gradeEssayAnswer(input.value, q.groups);
    essayScore += result.score;
    totalScore += result.score;

    let statusText = "kurang";
    if (result.score === 1) statusText = "benar";
    else if (result.score === 0.5) statusText = "cukup";

    feedbackEl.innerHTML = `<span class="${result.score === 1 ? 'correct' : result.score === 0.5 ? 'partial' : 'wrong'}">${statusText}</span> • inti cocok ${result.matched}/${result.total} • jawaban contoh: ${esc(q.modelAnswer)}`;
    feedback.push({
      title: `Essay ${q.num}`,
      status: statusText,
      detail: `Cocok ${result.matched}/${result.total}`
    });
  });

  const maxScore = mcqData.length + essayData.length;
  scoreText.textContent = `${totalScore.toFixed(1)} / ${maxScore}`;
  resultPanel.scrollIntoView({ behavior: "smooth", block: "start" });
  resultSummary.innerHTML = `
    <div class="summary-grid">
      <div class="summary-box">
        <div class="summary-label">Pilihan ganda</div>
        <div class="summary-value">${mcqCorrect} / ${mcqData.length}</div>
      </div>
      <div class="summary-box">
        <div class="summary-label">Essay</div>
        <div class="summary-value">${essayScore.toFixed(1)} / ${essayData.length}</div>
      </div>
      <div class="summary-box">
        <div class="summary-label">Total</div>
        <div class="summary-value">${totalScore.toFixed(1)} / ${maxScore}</div>
      </div>
    </div>`;

  feedbackList.innerHTML = feedback.map(item => `
    <div class="feedback-item">
      <strong>${esc(item.title)}</strong>
      <span>${esc(item.status)}</span>
      <p>${esc(item.detail)}</p>
    </div>
  `).join("");
}

